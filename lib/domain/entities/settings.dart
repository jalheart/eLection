class Settings {
  final int id;
  final String name;
  final String slogan;
  final String theme;
  final String logo;
  final bool passRequired;
  final String language;

  Settings({
    required this.id,
    required this.name,
    required this.slogan,
    required this.theme,
    required this.logo,
    required this.passRequired,
    required this.language,
  });
}
